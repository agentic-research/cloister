#!/usr/bin/env node
// SPDX-License-Identifier: AGPL-3.0-or-later
//
// Pin the demo's OCI layouts into its cluster.lock.toml (cloister-991e65,
// cloister-2af014). Usage: node pin-layouts.mjs <bundle>=<layout-dir> ...
//
// The images are built reproducibly (build-images.sh), so the digests are the
// same on every checkout and the lock is committed. This writes the lock in
// the shape `cluster resolve` writes — `[inputs.<bundle>.oci] identifier /
// version / digest` — reading each digest from the layout's own index.json
// rather than from any build log. Every rootfs row already recorded for an
// unchanged digest (one per platform) is kept, so a rebuild that reproduces
// the pins leaves the lock byte-for-byte unchanged.

import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseToml } from "smol-toml";

import { writeLockfile } from "../../../cli/lib/cluster/lockfile.mjs";

// Usage: node pin-layouts.mjs [--dir <cluster-dir>] <bundle>=<layout-dir | sha256:…> ...
//   <bundle>=<layout-dir>  pin a locally built layout's digest (from its index.json)
//   <bundle>=sha256:<hex>  pin a published image by digest, pulled later from its
//                          registry (`runtime import --bundle` with no --layout)
const argv = process.argv.slice(2);
const dirFlag = argv.indexOf("--dir");
const HERE = dirFlag >= 0
  ? resolve(argv.splice(dirFlag, 2)[1])
  : dirname(fileURLToPath(import.meta.url));
const cluster = parseToml(readFileSync(join(HERE, "cluster.toml"), "utf8"));
const lockPath = join(HERE, "cluster.lock.toml");

const inputs = {};
for (const arg of argv) {
  const [bundle, source] = arg.split("=");
  const decl = cluster.bundles.find((b) => b.name === bundle);
  if (!decl) throw new Error(`bundle "${bundle}" is not declared in cluster.toml`);
  let digest;
  if (source.startsWith("sha256:")) {
    digest = source;
  } else {
    const index = JSON.parse(readFileSync(resolve(source, "index.json"), "utf8"));
    if (!Array.isArray(index.manifests) || index.manifests.length !== 1) {
      throw new Error(`${source}: expected exactly one manifest in index.json (build-images.sh builds one platform)`);
    }
    digest = index.manifests[0].digest;
  }
  const oci = {
    identifier: decl.external.image,
    version: source.startsWith("sha256:") ? "published" : "local",
    digest,
  };
  inputs[bundle] = { oci };
}

const doc = {
  _comment:
    "GENERATED by a tools/dolt-grpc-demo build script from reproducibly built OCI " +
    "layouts and published digests (cloister-2af014). Committed: a clean build " +
    "pins the same digests.",
  schema: "cloister/lockfile/v1",
  cluster: cluster.metadata.name,
  version: cluster.metadata.version,
  inputs,
};
// A pin that moves is the demo no longer reproducing its committed lock (or a
// deliberate rebuild). Say so loudly before writing; git diff then shows it.
let previous = {};
try {
  previous = parseToml(readFileSync(lockPath, "utf8")).inputs ?? {};
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}
for (const [b, row] of Object.entries(inputs)) {
  const before = previous[b]?.oci?.digest;
  if (before && before !== row.oci.digest) {
    console.error(
      `pin-layouts: WARNING: ${b}'s pin changed: ${before} → ${row.oci.digest}. If this was not a ` +
        "deliberate change to the image, the build did not reproduce the committed lock " +
        "(tools/dolt-grpc-demo/microvm/README.md, reproducibility limit).",
    );
  }
}

// The one lock writer: carries every rootfs row already recorded for an
// unchanged image, and writes atomically.
writeLockfile(lockPath, doc);
console.log(`pin-layouts: wrote ${lockPath}`);
for (const [b, row] of Object.entries(inputs)) console.log(`  ${b}: ${row.oci.digest}`);
