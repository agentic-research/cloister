// Pin locally built OCI layouts into this demo's cluster.lock.toml
// (cloister-991e65). Usage: node pin-layouts.mjs <bundle>=<layout-dir> ...
//
// The demo's images are built on the operator's machine, so their digests are
// not stable across machines and the lock cannot honestly be committed. This
// writes a GENERATED lock (gitignored) in the shape `cluster resolve` writes —
// `[inputs.<bundle>.oci] identifier / version / digest` — reading each digest
// from the layout's own index.json rather than from any build log. A rootfs
// already recorded for an unchanged digest is kept, so re-running build.sh is
// idempotent.

import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseToml } from "smol-toml";

import { writeLockfile } from "../../../cli/lib/cluster/lockfile.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const cluster = parseToml(readFileSync(join(HERE, "cluster.toml"), "utf8"));
const lockPath = join(HERE, "cluster.lock.toml");

const inputs = {};
for (const arg of process.argv.slice(2)) {
  const [bundle, layout] = arg.split("=");
  const decl = cluster.bundles.find((b) => b.name === bundle);
  if (!decl) throw new Error(`bundle "${bundle}" is not declared in cluster.toml`);
  const index = JSON.parse(readFileSync(resolve(layout, "index.json"), "utf8"));
  if (!Array.isArray(index.manifests) || index.manifests.length !== 1) {
    throw new Error(`${layout}: expected exactly one manifest in index.json (build with --provenance=false --sbom=false)`);
  }
  const oci = {
    identifier: decl.external.image,
    version: "local",
    digest: index.manifests[0].digest,
  };
  inputs[bundle] = { oci };
}

const doc = {
  _comment:
    "GENERATED by tools/dolt-grpc-demo/microvm/build.sh from locally built OCI layouts. " +
    "Machine-local digests: do not commit (gitignored).",
  schema: "cloister/lockfile/v1",
  cluster: cluster.metadata.name,
  version: cluster.metadata.version,
  inputs,
};
// The one lock writer: carries a rootfs already recorded for an unchanged
// image, and writes atomically.
writeLockfile(lockPath, doc);
console.log(`pin-layouts: wrote ${lockPath}`);
for (const [b, row] of Object.entries(inputs)) console.log(`  ${b}: ${row.oci.digest}`);
