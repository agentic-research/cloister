#!/usr/bin/env node
// gen-adr-index.mjs — generate docs/adr/INDEX.md from each ADR's own frontmatter.
//
// Single source of truth: every ADR owns its status; this index is DERIVED, never
// hand-maintained. Replaces the per-ADR status lists that STATUS.md / CLAUDE.md /
// README.md hand-copied and let drift (the ADR-0030 "no code shipped" vs "epic
// closed" divergence is exactly what generation makes impossible).
//
// Lenient by design during Phase 0: reads YAML frontmatter `status:` OR the inline
// `**Status:**` line, and the `title:` field OR the `# ADR-NNNN — …` heading, so it
// works across the 26-YAML / 17-inline split before normalization finishes.
//
// Usage:
//   node scripts/gen-adr-index.mjs           rewrite docs/adr/INDEX.md
//   node scripts/gen-adr-index.mjs --check   regenerate in-memory + diff; exit 1 on
//                                            drift (the CI gate that replaces
//                                            lint-doc-counts's ADR-count policing)
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

// Ordered so the FIRST match wins when a status line names more than one state
// (e.g. "Amended … was Proposed" → Amended; "Accepted (Phase 1)" → Accepted).
export const STATUS_ENUM = ["Superseded", "Amended", "Accepted", "Deferred", "Rejected", "Reserved", "Draft", "Proposed"];

/** Parse one ADR's raw markdown into its index row fields. Pure — no fs. */
export function parseAdrText(num, file, text) {
  let title = "", statusRaw = "";

  const fm = text.match(/^---\n([\s\S]*?)\n---/);
  if (fm) {
    const t = fm[1].match(/^title:\s*["']?(.+?)["']?\s*$/m);
    if (t) title = t[1];
    const s = fm[1].match(/^status:\s*(.+?)\s*$/m);
    if (s) statusRaw = s[1];
  }
  if (title) {
    title = title.replace(/^ADR[-\s]?\d+\s*[:—–-]\s*/i, "").trim();
  } else {
    const h = text.match(/^#\s+ADR[-\s]?\d+\s*[—–:-]\s*(.+?)\s*$/m);
    if (h) title = h[1].trim();
  }
  if (!statusRaw) {
    const s = text.match(/^\s*(?:[-*]\s*)?\*\*Status:\*\*\s*(.+?)\s*$/m);
    if (s) statusRaw = s[1].replace(/[*_`]/g, "").trim();
  }

  let status = "—";
  for (const e of STATUS_ENUM) {
    if (new RegExp("\\b" + e + "\\b", "i").test(statusRaw)) { status = e; break; }
  }
  const date = (statusRaw.match(/\b(\d{4}-\d{2}-\d{2})\b/) || [])[1] || "";
  return { num, file, title: title || "(untitled)", status, date, statusRaw };
}

/** Read + parse every NNNN-*.md in an adr directory, sorted by number. */
export function readAllAdrs(adrDir) {
  return readdirSync(adrDir)
    .filter((f) => /^\d{4}-.*\.md$/.test(f))
    .sort()
    .map((f) => parseAdrText(parseInt(f.slice(0, 4), 10), f, readFileSync(join(adrDir, f), "utf8")));
}

/** Render the derived INDEX.md markdown from parsed ADR rows. Pure. */
export function buildIndexMd(adrs) {
  const rows = adrs
    .map((a) => `| [ADR-${String(a.num).padStart(4, "0")}](${a.file}) | ${a.title} | ${a.status}${a.date ? " · " + a.date : ""} |`)
    .join("\n");
  return `<!-- GENERATED by scripts/gen-adr-index.mjs — DO NOT EDIT. Run \`task adr:index\`. -->
# ADR index

${adrs.length} numbered ADRs. Each ADR's own frontmatter is the source of truth for
its **design** status; this table is derived from it. Implementation status lives in
beads + git (see each ADR's tracking bead), never typed here. Reserved-but-unfiled: 0032, 0037.

| ADR | Title | Status |
|---|---|---|
${rows}
`;
}

// ── CLI (only when invoked directly, not when imported by the test) ──────────
const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const adrDir = join(root, "docs/adr");
  const out = join(adrDir, "INDEX.md");
  const md = buildIndexMd(readAllAdrs(adrDir));

  if (process.argv.includes("--check")) {
    let cur = "";
    try { cur = readFileSync(out, "utf8"); } catch { /* missing = drift */ }
    if (cur.trim() !== md.trim()) {
      console.error("gen-adr-index: docs/adr/INDEX.md is STALE — run `node scripts/gen-adr-index.mjs` (or `task adr:index`)");
      process.exit(1);
    }
    console.log(`gen-adr-index: INDEX.md up to date (${md.match(/^\| \[ADR-/gm)?.length ?? 0} ADRs)`);
  } else {
    writeFileSync(out, md);
    console.log(`gen-adr-index: wrote docs/adr/INDEX.md (${md.match(/^\| \[ADR-/gm)?.length ?? 0} ADRs)`);
  }
}
