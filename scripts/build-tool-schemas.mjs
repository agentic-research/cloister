#!/usr/bin/env node
// scripts/build-tool-schemas.mjs
//
// Compile `src/tool-schemas/*.ts` zod schemas → JSON Schema, write a
// typed TS module that the runtime + manifest consume. Closes
// cloister-7ca96c (manifest↔handler schema drift). The TS module is
// the source of truth; the JSON Schema shipped to MCP clients is
// codegenned, never hand-written.
//
// Pipeline:
//
//   src/tool-schemas/index.ts (zod schemas)
//           │
//           │  zod v4 native z.toJSONSchema()
//           ▼
//   src/generated/tool-schemas.ts  (typed const: name → JSON Schema)
//
// `build-manifest.mjs` reads this generated module and merges the
// schemas into the route table by tool name — so the manifest's
// `inputSchemaJson` field becomes optional / advisory.
//
// We use zod v4's built-in `z.toJSONSchema()` rather than the older
// `zod-to-json-schema` package — that package is for zod v3 and emits
// empty objects against v4's revamped `_def` shape.
//
// Usage:
//   pnpm exec tsx scripts/build-tool-schemas.mjs
//
// Exit codes:
//   0 — wrote tool-schemas.ts
//   1 — schema compile failed

import { mkdirSync } from "node:fs";
import { writeGeneratedFile } from "./write-generated.mjs";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { z } from "zod";

const REPO        = process.cwd();
const INPUT_PATH  = resolve(REPO, "src/tool-schemas/index.ts");
const OUTPUT_FILE = resolve(REPO, "src/generated/tool-schemas.ts");

const mod = await import(pathToFileURL(INPUT_PATH).href).catch((e) => {
  console.error(`build-tool-schemas: failed to load ${INPUT_PATH}`);
  console.error(e?.message ?? e);
  process.exit(1);
});

const schemas = mod.schemas;
if (!schemas || typeof schemas !== "object") {
  console.error(`build-tool-schemas: ${INPUT_PATH} must export a \`schemas\` object`);
  process.exit(1);
}

const compiled = {};
for (const [name, schema] of Object.entries(schemas)) {
  // `target: "draft-7"` matches the JSON Schema flavor MCP tools/list
  // ships today. Don't change without an ADR — clients may rely on the
  // keyword set.
  const out = z.toJSONSchema(schema, { target: "draft-7" });
  // Strip `$schema` — MCP per-tool input schemas are inlined in the
  // tools/list response and clients don't expect a draft URI on each
  // one. Saves bytes on every tools/list response.
  delete out.$schema;
  compiled[name] = out;
}

// Sort tool names for deterministic output (diff-friendly).
const sorted = {};
for (const k of Object.keys(compiled).sort()) sorted[k] = compiled[k];

const body = JSON.stringify(sorted, null, 2);
const text = `// SPDX-License-Identifier: AGPL-3.0-or-later
//
// AUTO-GENERATED by scripts/build-tool-schemas.mjs. Do NOT edit by hand.
// Regenerate via \`task tool-schemas\` after editing src/tool-schemas/.
//
// Source: src/tool-schemas/index.ts (zod) → JSON Schema Draft 7.
// Closes cloister-7ca96c. The manifest's \`inputSchemaJson\` field is
// deprecated; this is the wire shape MCP clients see in tools/list.

/** Tool name → JSON Schema (Draft 7) for the tool's input arguments. */
export const toolSchemas: Record<string, unknown> = ${body} as const;

/** Every tool's name, sorted for stable iteration. */
export const toolNames: readonly string[] = Object.keys(toolSchemas) as readonly string[];
`;

mkdirSync(dirname(OUTPUT_FILE), { recursive: true });
writeGeneratedFile(OUTPUT_FILE, text);
console.log(`build-tool-schemas: wrote ${OUTPUT_FILE.replace(REPO + "/", "")}`);
console.log(`build-tool-schemas:   ${Object.keys(sorted).length} tool(s): ${Object.keys(sorted).join(", ")}`);
