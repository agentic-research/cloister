#!/usr/bin/env node
// scripts/dev-bootstrap.mjs
//
// Bootstraps a local dev environment per ADR-0014 v2 (cloister-125199).
// Generates a deterministic-per-user dev KEK and writes the URL spec into
// .env.local (gitignored). Idempotent — re-running reuses the existing
// key.
//
// Why this exists
// ───────────────
// Before ADR-0014 v2, `task dev` worked because config.capnp shipped a
// plaintext `VAULT_KEK_SECRET = "local-dev-only-CHANGE-IN-PRODUCTION"`
// placeholder. v2 deleted that binding. Without bootstrap, `task dev`
// now throws:
//
//   vault: VAULT_KEK_SOURCE is unset — per ADR-0014 v2, the vault DO
//   requires an explicit URL spec...
//
// Bootstrap fills the gap with a non-committed key local to the user's
// machine. The "no plaintext in committed config" rule still holds —
// .env.local is gitignored.
//
// What it does
// ────────────
//   1. Ensure .env.local exists
//   2. If DEV_VAULT_KEK is already set there, reuse it
//   3. Otherwise: generate 32 random bytes (hex), append to .env.local
//   4. Ensure VAULT_KEK_SOURCE=env://DEV_VAULT_KEK is set
//   5. If INTERLACE_ROOT_PUBKEY is unset, try `signet authority pubkey`
//      to materialize it from the local keystore (or remote authority
//      when SIGNET_AUTHORITY_URL is set). Skipped silently if signet
//      isn't on PATH — the lease gate then stays off (dev mode).
//   6. Print next steps
//
// Same URL-spec resolver code path as production (`env://` scheme); only
// the backend differs (env-binding for dev, keychain://`/file://`/etc.
// for prod). When ADR-0014 v2b lands (age-encrypted env carrier), this
// script will be updated to write an age-encrypted blob + a separate
// recipient spec. Until then, plain bytes-in-env-var works.
//
// Cross-platform: pure Node, no shells, no OS-specific dependencies.

import { randomBytes } from "node:crypto";
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ENV_LOCAL = resolve(process.cwd(), ".env.local");
const DEV_KEK_VAR = "DEV_VAULT_KEK";
const KEK_SOURCE_VAR = "VAULT_KEK_SOURCE";
const KEK_SOURCE_VAL = `env://${DEV_KEK_VAR}`;

// INTERLACE_ROOT_PUBKEY is the lease-gate trust anchor (see CLAUDE.md +
// docs/ARCHITECTURE.md). When set, the lease middleware verifies every
// authenticated request's cert chain against this public key. When unset,
// the gate is off (dev mode).
//
// The signet repo ships `signet authority pubkey` (signet-PR #131) which
// emits the master Ed25519 pubkey as base64. We invoke it here. If signet
// isn't on PATH, skip silently and let the gate stay off — many cloister
// dev workflows don't need lease verification.
const PUBKEY_VAR = "INTERLACE_ROOT_PUBKEY";
const SIGNET_BIN = process.env.SIGNET_BIN || "signet";
const SIGNET_AUTHORITY_URL = process.env.SIGNET_AUTHORITY_URL || ""; // when set, remote-fetch instead of local keystore
const PUBKEY_REFRESH = !!process.env.INTERLACE_PUBKEY_REFRESH; // force re-fetch even if already set

// notme-in-the-loop (cloister-d2e89a): when a local notme is running, its
// /internal/ca-bundle exposes the master key that BOTH signs the CA bundle
// cloister fetches AND (as the dev CA) issues the leases cloister verifies.
// Preferred over signet here because a mismatch between the pinned pubkey and
// the notme key that actually signed the bundle is precisely cloister-3ad090:
// signet's key and notme's dev key are independent, so an INTERLACE_ROOT_PUBKEY
// from signet cannot verify a bundle notme signed. Set NOTME_DEV_URL="" to
// disable the notme probe and use signet only.
const NOTME_DEV_URL = process.env.NOTME_DEV_URL ?? "http://localhost:8788";

function parseEnv(content) {
  const entries = new Map();
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq < 0) continue;
    const name = trimmed.slice(0, eq).trim();
    const value = trimmed.slice(eq + 1).trim();
    if (name) entries.set(name, value);
  }
  return entries;
}

function serializeEnv(entries, header) {
  const lines = header ? [header, ""] : [];
  for (const [name, value] of entries) {
    lines.push(`${name}=${value}`);
  }
  if (!lines[lines.length - 1].endsWith("\n")) lines.push("");
  return lines.join("\n");
}

const HEADER = [
  "# .env.local — generated by `task dev:bootstrap` per ADR-0014 v2.",
  "# DO NOT COMMIT. Gitignored. Per-user dev secrets only.",
  "#",
  "# Re-run `task dev:bootstrap` to regenerate. To wipe, delete this file.",
].join("\n");

const existing = existsSync(ENV_LOCAL) ? readFileSync(ENV_LOCAL, "utf8") : "";
const entries = parseEnv(existing);

let generated = false;
if (!entries.has(DEV_KEK_VAR) || !entries.get(DEV_KEK_VAR)) {
  const bytes = randomBytes(32);
  entries.set(DEV_KEK_VAR, bytes.toString("hex"));
  generated = true;
}

const sourceWas = entries.get(KEK_SOURCE_VAR);
entries.set(KEK_SOURCE_VAR, KEK_SOURCE_VAL);

// ── INTERLACE_ROOT_PUBKEY — lease-gate trust anchor ─────────────────
//
// Try to materialize from the local signet binary. Stays off if signet
// isn't installed — that's a supported dev mode.
function tryFetchInterlacePubkey() {
  const args = ["authority", "pubkey"];
  if (SIGNET_AUTHORITY_URL) args.push("--url", SIGNET_AUTHORITY_URL);

  const result = spawnSync(SIGNET_BIN, args, {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });

  if (result.error) {
    // ENOENT (signet not on PATH) or similar exec failure.
    return { ok: false, reason: "signet-not-found", detail: String(result.error) };
  }
  if (result.status !== 0) {
    // signet ran but failed — likely "master key not found" (no init
    // yet on local keystore) or HTTP failure for --url mode.
    return { ok: false, reason: "signet-error", detail: (result.stderr || "").trim() };
  }
  const pubkey = (result.stdout || "").trim();
  if (!pubkey) {
    return { ok: false, reason: "signet-empty", detail: "stdout was empty" };
  }
  return { ok: true, pubkey };
}

// Fetch notme's master pubkey from a locally-hosted notme worker. notme signs
// its JSON CABundle with this key; keys[keyId] IS the pin cloister must verify
// against. Returns { ok:false } (never throws) when notme isn't running.
async function tryFetchNotmePubkey() {
  if (!NOTME_DEV_URL) return { ok: false, reason: "notme-disabled", detail: "NOTME_DEV_URL empty" };
  let res;
  try {
    res = await fetch(`${NOTME_DEV_URL}/internal/ca-bundle`);
  } catch (e) {
    return { ok: false, reason: "notme-not-running", detail: String(e?.message ?? e) };
  }
  if (!res.ok) return { ok: false, reason: "notme-http", detail: `HTTP ${res.status}` };
  let bundle;
  try {
    bundle = await res.json();
  } catch (e) {
    return { ok: false, reason: "notme-bad-json", detail: String(e?.message ?? e) };
  }
  const key = bundle && bundle.keys ? bundle.keys[bundle.keyId] : undefined;
  if (typeof key !== "string" || !key) {
    return { ok: false, reason: "notme-shape", detail: "bundle has no keys[keyId]" };
  }
  return { ok: true, pubkey: key };
}

const pubkeyWas = entries.get(PUBKEY_VAR);
const shouldFetchPubkey = PUBKEY_REFRESH || !pubkeyWas;
let pubkeyOutcome = { kind: "kept" };
if (shouldFetchPubkey) {
  // Prefer a locally-hosted notme (it signs the bundle cloister verifies);
  // fall back to the signet keystore/URL.
  let fetched = await tryFetchNotmePubkey();
  let via = `local notme (${NOTME_DEV_URL})`;
  let notmeReason;
  if (!fetched.ok) {
    notmeReason = fetched.reason;
    fetched = tryFetchInterlacePubkey();
    via = SIGNET_AUTHORITY_URL || "local keystore (signet)";
  }
  if (fetched.ok) {
    entries.set(PUBKEY_VAR, fetched.pubkey);
    pubkeyOutcome = {
      kind: pubkeyWas ? "refreshed" : "fetched",
      pubkey: fetched.pubkey,
      via,
    };
  } else {
    pubkeyOutcome = { kind: "skipped", reason: fetched.reason, detail: fetched.detail, notmeReason };
  }
}

writeFileSync(ENV_LOCAL, serializeEnv(entries, HEADER), { mode: 0o600 });

console.log("dev-bootstrap:");
console.log(`  ${ENV_LOCAL}`);
if (generated) {
  console.log(`  ✓ Generated ${DEV_KEK_VAR} (32 bytes, hex)`);
} else {
  console.log(`  → Reusing existing ${DEV_KEK_VAR}`);
}
if (sourceWas !== KEK_SOURCE_VAL) {
  console.log(`  ✓ Set ${KEK_SOURCE_VAR}=${KEK_SOURCE_VAL}`);
} else {
  console.log(`  → ${KEK_SOURCE_VAR} already set correctly`);
}
switch (pubkeyOutcome.kind) {
  case "fetched":
    console.log(`  ✓ Set ${PUBKEY_VAR} from ${pubkeyOutcome.via} (lease gate ON)`);
    break;
  case "refreshed":
    console.log(`  ✓ Refreshed ${PUBKEY_VAR} from ${pubkeyOutcome.via} (INTERLACE_PUBKEY_REFRESH=1)`);
    break;
  case "kept":
    console.log(`  → ${PUBKEY_VAR} already set — kept (set INTERLACE_PUBKEY_REFRESH=1 to re-fetch)`);
    break;
  case "skipped":
    // Neither notme (local worker) nor signet produced a key.
    console.log(
      `  → ${PUBKEY_VAR} unset — no authority key available ` +
      `(notme: ${pubkeyOutcome.notmeReason ?? "n/a"}, signet: ${pubkeyOutcome.reason}). ` +
      `Lease gate OFF (dev mode).`,
    );
    console.log(`       start a local notme (\`wrangler dev\` in ../notme/worker --port 8788),`);
    console.log("       or install signet, or set INTERLACE_ROOT_PUBKEY=<base64> in .env.local.");
    if (pubkeyOutcome.detail) console.log(`       signet detail: ${pubkeyOutcome.detail.split("\n")[0]}`);
    break;
}
console.log("");
console.log("Next:");
console.log("  task dev          # workerd local on :8787 (sources .env.local)");
console.log("  task lint         # full test gate");
console.log("");
console.log("Note: tests stub KEK_HELPER (vitest.config.ts) and don't read");
console.log(".env.local — running tests doesn't require bootstrap.");
