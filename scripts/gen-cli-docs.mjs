#!/usr/bin/env node
// SPDX-License-Identifier: AGPL-3.0-or-later
//
// docs/reference/cli.md, derived from cli/surface.mjs.
//
//   node scripts/gen-cli-docs.mjs           write the page
//   node scripts/gen-cli-docs.mjs --check   fail if it is stale (the gate)
//
// One import, no subprocess. See cli-surface.mjs for why scraping `--help`
// would be the wrong shape.
//
// This closes a real gap rather than a hypothetical one: `cloister run` shipped
// and docs/reference/ had no CLI page at all, so the verb was documented
// nowhere. Deriving the page means the next verb cannot repeat that — it appears
// in the help and the docs together, or in neither.

import { readFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { writeGeneratedFile } from "./write-generated.mjs";
import { COMMANDS } from "../cli/surface.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = resolve(ROOT, "docs/reference/cli.md");

function render() {
  const out = [];
  out.push("<!-- GENERATED by scripts/gen-cli-docs.mjs from cli/surface.mjs — do not edit. -->");
  out.push("<!-- Regenerate: task cli:docs   ·   Drift gate: task cli:docs:check -->");
  out.push("");
  out.push("# cloister CLI");
  out.push("");
  out.push(
    "Derived from the single CLI surface declaration, so this page and " +
    "`cloister --help` cannot disagree. A command appears in both or in neither.",
  );
  out.push("");

  out.push("| Command | What it does |");
  out.push("|---|---|");
  for (const c of COMMANDS) {
    out.push(`| [\`cloister ${c.name}\`](#cloister-${c.name.replace(/\s+/g, "-")}) | ${c.summary} |`);
  }
  out.push("");

  for (const c of COMMANDS) {
    out.push(`## cloister ${c.name}`);
    out.push("");
    out.push("```");
    out.push(c.usage);
    out.push("```");
    out.push("");
    out.push(c.detail ?? c.summary);
    out.push("");
    if (c.flags?.length) {
      out.push("| Flag | | |");
      out.push("|---|---|---|");
      for (const f of c.flags) {
        const val = f.value ? ` \`${f.value}\`` : "";
        out.push(`| \`${f.flag}\`${val} | ${f.required ? "**required**" : ""} | ${f.summary} |`);
      }
      out.push("");
    }
    if (c.seeAlso) {
      // The page lives at docs/reference/cli.md, so a repo-root path has to be
      // made relative to THAT directory. Stripping only `docs/reference/`
      // silently produced a link resolving to docs/reference/docs/adr/… for any
      // target outside this directory — which lint:doc-links caught the first
      // time a command pointed at an ADR.
      const rel = c.seeAlso.startsWith("docs/reference/")
        ? c.seeAlso.slice("docs/reference/".length)
        : c.seeAlso.replace(/^docs\//, "../");
      out.push(`See also: [\`${c.seeAlso}\`](${rel})`);
      out.push("");
    }
  }

  out.push("---");
  out.push("");
  out.push(
    "`--help` on any command is side-effect free by contract: it prints and exits " +
    "without minting a credential, writing a file, or launching anything. That is " +
    "asserted by test, because it has been false before (`cloister-eb33d4`).",
  );
  return `${out.join("\n")}\n`;
}

function main() {
  const body = render();
  if (process.argv.includes("--check")) {
    let current = null;
    try {
      current = readFileSync(OUTPUT, "utf8");
    } catch {
      // lint-allow-silent: an absent file is the drift being reported below,
      // and the message there is more useful than a raw ENOENT.
    }
    if (current !== body) {
      process.stderr.write(
        `gen-cli-docs: DRIFT — docs/reference/cli.md does not match the CLI surface ` +
        `declaration.\n  regenerate: task cli:docs\n`,
      );
      process.exit(1);
    }
    process.stdout.write("gen-cli-docs: OK — docs/reference/cli.md matches the declaration\n");
    return;
  }
  writeGeneratedFile(OUTPUT, body);
  process.stdout.write(`gen-cli-docs: wrote docs/reference/cli.md (${COMMANDS.length} commands)\n`);
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) main();
