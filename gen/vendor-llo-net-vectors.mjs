#!/usr/bin/env node
// SPDX-License-Identifier: AGPL-3.0-or-later
//
// gen/vendor-llo-net-vectors.mjs — copy ley-line-open's leyline-net/v1 test
// vectors into cloister, from the release cloister pins.
//
// LLO owns the ToolCall / ToolResult / Manifest wire (leyline-schema-spec
// `leyline-net/v1`). Its `wire/frames.md` pins every vector in two byte forms,
// `reference` (sections at their declared sizes) and `canonical` (trailing
// zero words truncated), and says: "Decoders MUST accept both". cloister is
// named there as the second implementation. Its own cross-check only ever
// loaded the reference form, so three of its hand-written decoders refused
// canonical bytes, and nothing noticed until rosary, which writes canonical
// capnp, answered a real call.
//
// So the vectors are vendored, not re-derived: test/wire/llo-net-vectors.test.ts
// runs every one of them, in both forms.
//
// Reads the files from git at the release commit, not from the working tree,
// so the LLO checkout can be on any branch (llo-bump reads it the same way).
// Refuses any file that does not match LLO's own VECTORS.sha256. `task
// llo:bump` calls this with the commit it has just resolved.
//
// Usage: node gen/vendor-llo-net-vectors.mjs <ley-line-open checkout>

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { writeGeneratedFile } from "../cli/lib/atomic-write.mjs";
import { startedAsScript } from "../cli/lib/started-as-script.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const VECTORS_FIXTURE = resolve(ROOT, "test/wire/fixtures/llo-net-vectors.json");
const SPEC_DIR = "rs/ll-core/schema-spec/leyline-net/v1/test-vectors";
const FORMS = ["reference", "canonical"];

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

/**
 * @param {string} lloRoot a ley-line-open checkout
 * @param {{tag: string, commit: string, dry?: boolean}} at the release it must be at
 * @returns {{count: number, unchanged: boolean}}
 */
export function vendorNetVectors(lloRoot, { tag, commit, dry = false }) {
  const at = (path) => execFileSync("git", ["-C", lloRoot, "show", `${commit}:${SPEC_DIR}/${path}`],
    { maxBuffer: 16 * 1024 * 1024 });
  const pinned = new Map(
    at("VECTORS.sha256").toString("utf8")
      .split("\n")
      .filter(Boolean)
      .map((line) => {
        const [digest, path] = line.trim().split(/\s+/);
        return [path, digest];
      }),
  );
  // VECTORS.sha256 also covers the spec's other files (digests.json, the
  // capnp source); the vectors are the .bin files under each form.
  const isVector = (path) => FORMS.some((form) => path.startsWith(`${form}/`)) && path.endsWith(".bin");
  const names = [...new Set([...pinned.keys()].filter(isVector).map((path) => path.split("/").pop()))].sort();
  const vectors = {};
  for (const name of names) {
    vectors[name.replace(/\.bin$/, "")] = Object.fromEntries(FORMS.map((form) => {
      const path = `${form}/${name}`;
      const bytes = at(path);
      if (!pinned.has(path)) throw new Error(`vendor-llo-net-vectors: ${path} is not in LLO's VECTORS.sha256`);
      if (sha256(bytes) !== pinned.get(path)) throw new Error(`vendor-llo-net-vectors: ${path} does not match LLO's VECTORS.sha256`);
      return [form, { sha256: pinned.get(path), base64: bytes.toString("base64") }];
    }));
  }
  if (names.length < 12) throw new Error(`vendor-llo-net-vectors: found ${names.length} vectors, expected at least 12`);

  const body = JSON.stringify({
    _comment: "Generated by gen/vendor-llo-net-vectors.mjs from ley-line-open leyline-net/v1. Do not edit; bump with `task llo:bump`.",
    version: tag,
    commit,
    source: `${SPEC_DIR}`,
    vectors,
  }, null, 2) + "\n";
  let previous = "";
  try { previous = readFileSync(VECTORS_FIXTURE, "utf8"); } catch { /* lint-allow-silent: absent on first vendor */ }
  if (!dry && previous !== body) writeGeneratedFile(VECTORS_FIXTURE, body);
  return { count: names.length, unchanged: previous === body };
}

if (startedAsScript(import.meta.url)) {
  const lloRoot = process.argv[2];
  if (!lloRoot) {
    console.error("usage: node gen/vendor-llo-net-vectors.mjs <ley-line-open checkout>");
    process.exit(2);
  }
  const tag = JSON.parse(readFileSync(resolve(ROOT, "schema-bridge.lock.json"), "utf8")).version;
  const commit = execFileSync("git", ["-C", lloRoot, "rev-parse", `${tag}^{commit}`], { encoding: "utf8" }).trim();
  const { count, unchanged } = vendorNetVectors(lloRoot, { tag, commit });
  console.log(`vendor-llo-net-vectors: ${count} vectors × ${FORMS.length} forms from ${tag} (${commit.slice(0, 12)}), ${unchanged ? "unchanged" : "written"}`);
}
