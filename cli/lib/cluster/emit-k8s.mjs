//
// cli/lib/cluster/emit-k8s.mjs — the forwarded `kubernetes` placement
// (ADR-0070 §2 + §4, cloister-991e65).
//
// Forwarded means forwarded. The operator's rendered manifest is the workload
// spec; cloister parses it ONLY to check the edges it declares (does the
// Service carry each declared port, by name, number and appProtocol?) and
// copies it byte-for-byte. Everything cloister adds is an overlay of its own
// objects, one namespace per bundle:
//
//   - the Namespace, unless the manifest declares it;
//   - a default-deny-ingress NetworkPolicy for that namespace;
//   - per declared connection INTO the bundle from another kubernetes-placed
//     bundle: a NetworkPolicy admitting the source's pods (namespace + the
//     source Service's selector) to the target's pods (the target Service's
//     selector) on that port, TCP.
//
// That is the `policy` strength of ADR-0070 §3: a reachable peer is refused
// unless an edge was declared. It holds only where the CNI enforces
// NetworkPolicy (kind >= v0.24 does).
//
// No env vars are emitted. Env lowering is a later slice; until then the
// operator's manifest carries the address itself, and the addresses it
// carries are held to the declared connections (checkAddresses).
//
// A `knative` placement is CHECKED here and never lowered (ADR-0070 §2–3,
// issue #311). Its strength is "none": the declared port and appProtocol are
// held to the Knative Service, and no file, namespace or policy is written.

import { basename } from "node:path";
import { parseAllDocuments, stringify } from "yaml";

import { addressesIn, clusterService, containerStrings, isObject } from "./manifest-addresses.mjs";
import {
  isExposed,
  placementFor,
  joinable,
  KNATIVE_POD_LABEL,
  requireManifest,
  portsFor,
  refuseCrossPlacement,
} from "./connections.mjs";

const MANAGED_BY = { "app.kubernetes.io/managed-by": "cloister" };
const HEADER = "# Generated by `cloister cluster k8s` (ADR-0070 §4). Do not edit.\n";

/** The objects this emitter reads. Everything else is forwarded unread. */
const NAMESPACE = Object.freeze({ group: "", kind: "Namespace" });
const SERVICE = Object.freeze({ group: "", kind: "Service" });

const KNATIVE_SERVICE = Object.freeze({ group: "serving.knative.dev", kind: "Service" });

/** The port a Knative Service is reached on inside the cluster, whatever its container listens on. */
const KNATIVE_PORT = 80;
/** The label, and its value, that keeps a Knative Service off every external route. */
export const KNATIVE_VISIBILITY_LABEL = "networking.knative.dev/visibility";
export const KNATIVE_CLUSTER_LOCAL = "cluster-local";

/**
 * Which Knative wire each blessed appProtocol label can run on. A Knative
 * Service serves HTTP on one port, and names that port `http1` (the default)
 * or `h2c`. A label mapped to `[]` is not HTTP and cannot be a Knative port at
 * all. A test holds this table to the blessed set, so a new label must be
 * placed here before it can be declared on a knative bundle. Vendor (`x-`)
 * labels are not in it: what they need is unknown, so they are not checked.
 */
export const KNATIVE_WIRES = Object.freeze({
  "art.http": ["http1"],
  "art.http2": ["h2c"],
  "art.grpc": ["h2c"],
  "art.mcp-jsonrpc": ["http1", "h2c"],
  "art.interlace-capnp": [],
  "art.capnp-uds": [],
  "art.tcp": [],
  "art.tls": [],
  "art.mysql": [],
});

/** Parse a multi-document YAML manifest into plain objects, failing by name. */
export function parseManifest(text, label) {
  const docs = parseAllDocuments(text);
  const objects = [];
  for (const doc of docs) {
    if (doc.errors.length > 0) {
      throw new Error(`${label}: YAML parse error: ${doc.errors[0].message}`);
    }
    const obj = doc.toJS();
    if (obj === null || obj === undefined) continue; // empty document
    collect(obj, objects, label);
  }
  return objects;
}

/** `kubectl get <kind> -o yaml` wraps what it finds in one of these. */
const LIST = Object.freeze({ group: "", kind: "List" });

/** Add `obj` to `objects`, or the objects it wraps when it is a core `v1` List. */
function collect(obj, objects, label) {
  if (typeof obj !== "object" || obj === null || Array.isArray(obj) || typeof obj.kind !== "string" || typeof obj.apiVersion !== "string") {
    throw new Error(`${label}: every document must be a Kubernetes object with an apiVersion and a kind`);
  }
  if (!isObject(obj, LIST)) {
    objects.push(obj);
    return;
  }
  if (!Array.isArray(obj.items)) throw new Error(`${label}: a List with no items`);
  for (const item of obj.items) collect(item, objects, label);
}

function isLabelMap(v) {
  return v && typeof v === "object" && !Array.isArray(v) && Object.keys(v).length > 0
    && Object.values(v).every((x) => typeof x === "string");
}

/**
 * Check one kubernetes-placed bundle's manifest against its declarations, and
 * return what the overlay needs: whether it declares its own Namespace, the
 * Service selector, and each declared port's pod-side port.
 */
export function inspectManifest(bundle, objects, label) {
  const ns = bundle.name;
  let declaresNamespace = false;
  const services = [];
  for (const obj of objects) {
    const name = obj.metadata?.name ?? "<unnamed>";
    if (isObject(obj, KNATIVE_SERVICE)) {
      // Never read as a core Service, and never fenced with policies written
      // for a different request path.
      throw new Error(
        `${label}: Knative Service "${name}" (${obj.apiVersion}) cannot be a "kubernetes" placement. ` +
          `Knative routes a request through its own ingress and activator, so the pod-to-pod ` +
          `NetworkPolicies this command writes would not describe the path, and the default-deny ` +
          `policy would cut it. Place bundle "${ns}" kind = "knative": its connections are checked ` +
          `and nothing is enforced (strength "none"). Or give it a Deployment and a core v1 Service.`,
      );
    }
    if (isObject(obj, NAMESPACE)) {
      if (name !== ns) {
        throw new Error(
          `${label}: declares Namespace "${name}", but bundle "${ns}" lives in namespace "${ns}" ` +
            `(one namespace per bundle, named after it)`,
        );
      }
      declaresNamespace = true;
      continue;
    }
    const objNs = obj.metadata?.namespace;
    if (objNs !== undefined && objNs !== ns) {
      throw new Error(
        `${label}: ${obj.kind} "${name}" is in namespace "${objNs}", but bundle "${ns}"'s ` +
          `objects must be in namespace "${ns}" or declare none`,
      );
    }
    if (isObject(obj, SERVICE)) services.push(obj);
  }

  // A bundle that exposes no port (a job, a worker that only calls out) is
  // reached by nothing, so it needs no Service. Its pods are every pod in its
  // namespace: one namespace per bundle, so the empty selector means the same.
  if (services.length === 0 && !bundle.ports.some(isExposed)) {
    return { declaresNamespace, selector: {}, podPorts: new Map(), service: null, namespace: ns };
  }
  if (services.length !== 1) {
    throw new Error(
      `${label}: bundle "${ns}" must declare exactly one core v1 Service (found ${services.length}); ` +
        `its selector is what the NetworkPolicies select`,
    );
  }
  const svc = services[0];
  const svcName = svc.metadata?.name ?? "<unnamed>";
  const selector = svc.spec?.selector;
  if (!isLabelMap(selector)) {
    throw new Error(`${label}: Service "${svcName}" has no spec.selector; NetworkPolicies need one to select pods`);
  }

  const podPorts = new Map();
  const svcPorts = Array.isArray(svc.spec?.ports) ? svc.spec.ports : [];
  for (const p of bundle.ports.filter(isExposed)) {
    if (p.expose === "edge") {
      // Publishing a port outside the cluster (a NodePort plus kind
      // extraPortMappings) overlaps the broker work; refused, not guessed.
      throw new Error(
        `${label}: bundle "${ns}" port "${p.name}" has expose = "edge", which \`cluster k8s\` does ` +
          `not lower yet (a NodePort plus kind extraPortMappings; tracked with cloister-55424e). ` +
          `Use expose = "cluster" for a kubernetes placement, or place the bundle microvm, where ` +
          `\`cluster up\` publishes it on 127.0.0.1.`,
      );
    }
    const sp = svcPorts.find((x) => x?.name === p.name);
    const where = `${label}: Service "${svcName}" port "${p.name}"`;
    if (!sp) {
      throw new Error(`${where} is missing — bundle "${ns}" declares port "${p.name}" (${p.port}) with expose "${p.expose}"`);
    }
    if (sp.port !== p.port) {
      throw new Error(`${where} has port ${sp.port}, but cluster.toml declares ${p.port}`);
    }
    if (sp.appProtocol !== p.appProtocol) {
      throw new Error(
        `${where} has appProtocol ${JSON.stringify(sp.appProtocol ?? null)}, but cluster.toml declares "${p.appProtocol}"`,
      );
    }
    // NetworkPolicy ports match the POD's port, which is the Service's
    // targetPort (a number or a container port name), defaulting to `port`.
    podPorts.set(p.name, sp.targetPort ?? sp.port);
  }
  return { declaresNamespace, selector, podPorts, service: svcName, namespace: ns };
}

/**
 * Check one knative-placed bundle's manifest against its declarations. Nothing
 * is lowered for it: a knative placement has strength "none" (ADR-0070 §3), so
 * there is no policy to write and no namespace this command owns. Returns what
 * a peer dials, for the report.
 */
export function inspectKnative(bundle, objects, label) {
  const all = objects.filter((obj) => isObject(obj, KNATIVE_SERVICE));
  // One Knative Service is the bundle's, whatever it is called. A file with
  // several is one export of a whole stack, shared by the bundles in it: the
  // bundle's Service is then the one with its name, and nothing is guessed.
  const services = all.length > 1 ? all.filter((obj) => obj.metadata?.name === bundle.name) : all;
  if (services.length !== 1) {
    const core = objects.some((obj) => isObject(obj, SERVICE));
    const names = all.map((obj) => JSON.stringify(obj.metadata?.name ?? "<unnamed>")).join(", ");
    throw new Error(
      `${label}: bundle "${bundle.name}" is placed "knative" and must declare exactly one Knative ` +
        `Service (serving.knative.dev; found ${all.length})` +
        (all.length === 0 && core ? `. It declares a core v1 Service: place it kind = "kubernetes"` : "") +
        (all.length > 1 ? `. With several in one manifest, the one named "${bundle.name}" is used, and ` +
          `${services.length === 0 ? "none is" : "more than one is"} (found: ${names})` : ""),
    );
  }
  const svc = services[0];
  const name = svc.metadata?.name ?? "<unnamed>";
  const where = `${label}: Knative Service "${name}"`;

  const containers = svc.spec?.template?.spec?.containers;
  const ports = (Array.isArray(containers) ? containers : []).flatMap((c) => (Array.isArray(c?.ports) ? c.ports : []));
  if (ports.length > 1) {
    throw new Error(`${where} declares ${ports.length} container ports; a Knative Service serves exactly one`);
  }
  const portName = ports[0]?.name ?? "";
  if (!["", "http1", "h2c"].includes(portName)) {
    throw new Error(`${where} names its container port ${JSON.stringify(portName)}; Knative reads only "http1" or "h2c" there`);
  }
  const wire = portName === "h2c" ? "h2c" : "http1";

  const exposed = bundle.ports.filter(isExposed);
  if (exposed.length > 1) {
    throw new Error(
      `${where}: bundle "${bundle.name}" declares ${exposed.length} exposed ports ` +
        `(${exposed.map((p) => p.name).join(", ")}); a Knative Service serves exactly one`,
    );
  }
  for (const p of exposed) {
    const port = `${where}: port "${p.name}"`;
    // Whether it can be reached from outside the cluster is Knative's own
    // route visibility, which the Service states with a label. `expose` says
    // which is meant, and the manifest must agree (ADR-0070 §2 amendment).
    const visibility = svc.metadata?.labels?.[KNATIVE_VISIBILITY_LABEL];
    if (p.expose === "edge" && visibility === KNATIVE_CLUSTER_LOCAL) {
      throw new Error(
        `${port} has expose = "edge", but the Service is labelled ${KNATIVE_VISIBILITY_LABEL}: ${KNATIVE_CLUSTER_LOCAL}, ` +
          `so it has no route from outside the cluster. Remove the label, or use expose = "cluster"`,
      );
    }
    if (p.expose !== "edge" && visibility !== KNATIVE_CLUSTER_LOCAL) {
      throw new Error(
        `${port} has expose = "${p.expose}", but the Service is not labelled ` +
          `${KNATIVE_VISIBILITY_LABEL}: ${KNATIVE_CLUSTER_LOCAL}. Without it Knative gives the Service a route from ` +
          `outside the cluster. Add the label to its metadata.labels, or use expose = "edge" if that is intended`,
      );
    }
    if (p.port !== KNATIVE_PORT) {
      const container = typeof ports[0]?.containerPort === "number" ? ` (its container port ${ports[0].containerPort} is not what a peer dials)` : "";
      throw new Error(
        `${port} is dialled on ${p.port} in cluster.toml, but a Knative Service is reached on ` +
          `port ${KNATIVE_PORT} inside the cluster${container}. Add a [[bundles.placements.ports]] row ` +
          `to this placement with name = "${p.name}" and port = ${KNATIVE_PORT}: the bundle's port stays what the workload listens on`,
      );
    }
    // With the dialled number set apart, the bundle's own port is what the
    // container listens on, and the manifest must agree when it says.
    const listens = p.listen ?? p.port;
    if (listens !== p.port && typeof ports[0]?.containerPort === "number" && ports[0].containerPort !== listens) {
      throw new Error(
        `${port} listens on ${listens} in cluster.toml, but the Service's container port is ${ports[0].containerPort}`,
      );
    }
    if (Object.hasOwn(KNATIVE_WIRES, p.appProtocol)) {
      const wires = KNATIVE_WIRES[p.appProtocol];
      if (wires.length === 0) {
        throw new Error(`${port} has appProtocol "${p.appProtocol}", which is not HTTP; a Knative Service serves HTTP only`);
      }
      if (!wires.includes(wire)) {
        throw new Error(
          `${port} has appProtocol "${p.appProtocol}", which needs the container port named ` +
            `${wires.map((w) => `"${w}"`).join(" or ")}, but the Service serves ${wire}` +
            (portName === "" ? " (an unnamed container port is http1)" : ""),
        );
      }
    }
  }
  const namespace = typeof svc.metadata?.namespace === "string" ? svc.metadata.namespace : "";
  // The other Knative Services in a shared file are other bundles: their
  // containers are not this bundle's, so their strings are not read as its own.
  const own = objects.filter((obj) => obj === svc || !isObject(obj, KNATIVE_SERVICE));
  return { service: name, namespace, wire, port: KNATIVE_PORT, objects: own };
}

/**
 * Hold the addresses each handled bundle's containers are told to dial to the
 * declared connections (ADR-0070 §2, issue #311).
 *
 * An address is resolved to a bundle only by exact match on that bundle's
 * Service name and namespace: the cluster DNS name, with or without
 * `.cluster.local`, anywhere in a value; `<service>.<namespace>` or the bare
 * `<service>` (same namespace only) where the value puts it in host position.
 *
 * - An address that resolves to another handled bundle needs a declared
 *   connection to it in this env, and its port, when stated, must be one a
 *   declared connection reaches. Otherwise the build fails by name: this is a
 *   manifest that dials something `cluster.toml` does not say it dials.
 * - A cluster DNS name that resolves to no handled bundle is reported and not
 *   checked: it may be a typo, or a service cloister does not place.
 * - A declared connection no value names is reported, not refused: the
 *   address may come from a ConfigMap or Secret outside the manifest (those
 *   references are returned in `unread`) or from a file.
 *
 * @param {Array<{name, service, namespace, label, objects, ports}>} nodes
 * @param {Array<{name, from, to, port}>} edges this env's handled connections
 */
function checkAddresses(nodes, edges, env) {
  const references = [];
  const unread = [];
  const seen = new Set();
  const resolve = (source, address) => {
    const named = clusterService(address.host);
    const wanted = named ?? (address.hostPosition ? shortName(source, address.host) : null);
    if (!wanted) return { cluster: false, targets: [] };
    return { cluster: Boolean(named), targets: nodes.filter((n) => n.service === wanted.service && n.namespace === wanted.namespace) };
  };
  for (const source of nodes) {
    const resolved = containerStrings(source.objects);
    for (const u of resolved.unread) unread.push({ bundle: source.name, ...u });
    for (const { container, where, value } of resolved.strings) {
      for (const address of addressesIn(value)) {
        const { cluster, targets } = resolve(source, address);
        const shown = `${address.host}${address.port === null ? "" : `:${address.port}`}`;
        const from = `${source.label}: container ${JSON.stringify(container)} ${where} names ${shown}`;
        if (targets.length > 1) {
          throw new Error(`${from}, which is the Service of more than one bundle (${targets.map((t) => `"${t.name}"`).join(", ")})`);
        }
        const target = targets[0];
        if (target?.name === source.name) continue;
        const key = [source.name, container, where, shown].join("\u0000");
        if (!target) {
          if (cluster && !seen.has(key)) references.push({ bundle: source.name, container, where, address: shown, to: null, connections: [] });
          seen.add(key);
          continue;
        }
        const declared = edges.filter((e) => e.from === source.name && e.to === target.name);
        if (declared.length === 0) {
          throw new Error(
            `${from} (bundle "${target.name}"), but cluster.toml declares no connection from ` +
              `"${source.name}" to "${target.name}" for env "${env}"`,
          );
        }
        const portOf = (edge) => target.ports.find((p) => p.name === edge.port)?.port;
        const reached = address.port === null ? declared : declared.filter((e) => portOf(e) === address.port);
        if (reached.length === 0) {
          throw new Error(
            `${from} (bundle "${target.name}"), but the declared ` +
              `${declared.map((e) => `connection "${e.name}" reaches port ${portOf(e)}`).join(" and ")}`,
          );
        }
        if (!seen.has(key)) references.push({ bundle: source.name, container, where, address: shown, to: target.name, connections: reached.map((e) => e.name) });
        seen.add(key);
      }
    }
  }
  const named = new Set(references.flatMap((r) => r.connections.map((c) => `${r.bundle}\u0000${c}`)));
  const unreferenced = edges.filter((e) => !named.has(`${e.from}\u0000${e.name}`)).map((e) => ({ name: e.name, from: e.from, to: e.to }));
  return { references, unreferenced, unread };
}

/** `<service>.<namespace>`, or a bare `<service>` in the source's own namespace; else null. */
function shortName(source, host) {
  const labels = host.split(".");
  if (labels.length === 2) return { service: labels[0], namespace: labels[1] };
  if (labels.length === 1 && source.namespace !== "") return { service: host, namespace: source.namespace };
  return null;
}

function namespaceObject(ns) {
  return { apiVersion: "v1", kind: "Namespace", metadata: { name: ns, labels: { ...MANAGED_BY } } };
}

function defaultDeny(ns) {
  return {
    apiVersion: "networking.k8s.io/v1",
    kind: "NetworkPolicy",
    metadata: { name: "cloister-default-deny-ingress", namespace: ns, labels: { ...MANAGED_BY } },
    spec: { podSelector: {}, policyTypes: ["Ingress"] },
  };
}

function allowEdge(conn, source, target, podPort) {
  return {
    apiVersion: "networking.k8s.io/v1",
    kind: "NetworkPolicy",
    metadata: {
      name: `cloister-allow-${conn.from}-${conn.name}`,
      namespace: target.name,
      labels: { ...MANAGED_BY },
    },
    spec: {
      podSelector: { matchLabels: { ...target.selector } },
      policyTypes: ["Ingress"],
      ingress: [
        {
          from: [
            {
              namespaceSelector: { matchLabels: { "kubernetes.io/metadata.name": source.name } },
              podSelector: { matchLabels: { ...source.selector } },
            },
          ],
          ports: [{ protocol: "TCP", port: podPort }],
        },
      ],
    },
  };
}

function yamlDocs(objects) {
  return HEADER + objects.map((o) => stringify(o, { lineWidth: 0 })).join("---\n");
}

/** The placement kinds this command handles: one it lowers, one it checks. */
const HANDLED = Object.freeze(["kubernetes", "knative"]);

/**
 * Lower every kubernetes-placed bundle for `env`, and check every
 * knative-placed one.
 *
 * @param {object} opts
 * @param {Array} opts.bundles   checkable bundles (name, ports, placements, executionMode)
 * @param {Array} opts.connections normalized connections
 * @param {string} opts.env
 * @param {(path: string) => string} opts.readManifest reads a cluster-dir-relative path
 * @returns {{files: Array<{path: string, content: string}>, checked: Array, references: Array, unreferenced: Array}}
 *   `files` is deterministic: kubernetes bundles in declaration order, files
 *   `<bundle>/00-namespace.yaml` (when needed), `<bundle>/10-<manifest
 *   basename>`, `<bundle>/20-networkpolicy.yaml`. A knative bundle gets the
 *   first two and no policy. `applies` says which namespace each directory is
 *   applied in. `checked` lists each knative bundle with what a peer dials and
 *   the connections into and out of it. `references` and `unreferenced` are what the
 *   containers' own strings say about the graph (see checkAddresses).
 */
export function lowerK8s({ bundles: declared, connections, env, readManifest }) {
  // Every check below is about what a PEER dials. A port's number here is the
  // one dialled in this env, which a placement row may set apart from the
  // number the workload listens on (ADR-0074 §7); `listen` keeps the latter.
  const bundles = declared.map((b) => ({ ...b, ports: portsFor(b, env) }));
  const placed = bundles.filter((b) => placementFor(b, env) === "kubernetes");
  const knative = bundles.filter((b) => placementFor(b, env) === "knative");

  // Edges that touch a bundle this command handles: both ends must have the
  // same kind here. An edge into or out of another placement is legal in the
  // graph and refused by every emitter until something joins the two.
  const edges = [];
  for (const c of connections) {
    const from = bundles.find((b) => b.name === c.from);
    const fromKind = placementFor(from, env);
    const target = c.targets.find((t) => t.env === env);
    if (!target) {
      if (HANDLED.includes(fromKind)) {
        throw new Error(
          `connection "${c.name}" (from "${c.from}") declares no target for env "${env}" ` +
            `(declared: ${c.targets.map((t) => t.env).join(", ")})`,
        );
      }
      continue;
    }
    const toKind = placementFor(bundles.find((b) => b.name === target.bundle), env);
    if (!HANDLED.includes(fromKind) && !HANDLED.includes(toKind)) continue;
    // kubernetes and knative share a cluster network, so an edge between
    // them is lowered here: a knative caller is admitted by the kubernetes
    // target's policy, and a kubernetes caller reaches a knative target that
    // has none (ADR-0070 §2 amendment).
    if (!joinable(fromKind, toKind)) refuseCrossPlacement(c, c.from, fromKind, target.bundle, toKind, env);
    edges.push({ name: c.name, from: c.from, to: target.bundle, port: target.port });
  }

  // Each manifest is read and parsed once.
  const manifests = new Map();
  for (const b of [...placed, ...knative]) {
    const path = requireManifest(b, env, "cloister cluster k8s");
    const label = `bundle "${b.name}" manifest ${path}`;
    const text = readManifest(path);
    manifests.set(b.name, { path, label, text, objects: parseManifest(text, label) });
  }

  const ownObjects = new Map();
  const checked = knative.map((b) => {
    const { label, objects } = manifests.get(b.name);
    const { objects: own, ...found } = inspectKnative(b, objects, label);
    ownObjects.set(b.name, own);
    return {
      bundle: b.name,
      ...found,
      connectionsIn: edges.filter((e) => e.to === b.name).map((e) => ({ name: e.name, from: e.from })),
      connectionsOut: edges.filter((e) => e.from === b.name).map((e) => ({ name: e.name, to: e.to })),
    };
  });

  const inspected = new Map();
  for (const b of placed) {
    const { label, objects } = manifests.get(b.name);
    inspected.set(b.name, { name: b.name, ...inspectManifest(b, objects, label) });
  }

  const node = (b, info) => ({
    name: b.name, service: info.service, namespace: info.namespace, ports: b.ports,
    ...manifests.get(b.name),
    ...(ownObjects.has(b.name) ? { objects: ownObjects.get(b.name) } : {}),
  });
  const { references, unreferenced, unread } = checkAddresses(
    [...placed.map((b) => node(b, inspected.get(b.name))), ...knative.map((b) => node(b, checked.find((k) => k.bundle === b.name)))],
    edges,
    env,
  );

  const files = [];
  for (const b of placed) {
    const info = inspected.get(b.name);
    const { path, text } = manifests.get(b.name);
    if (!info.declaresNamespace) {
      files.push({ path: `${b.name}/00-namespace.yaml`, content: yamlDocs([namespaceObject(b.name)]) });
    }
    files.push({ path: `${b.name}/10-${basename(path)}`, content: text });

    const policies = [defaultDeny(b.name)];
    for (const c of connections) {
      const t = c.targets.find((x) => x.env === env);
      if (!t || t.bundle !== b.name) continue;
      // The caller's pods: a kubernetes bundle's by its Service selector, in
      // its own namespace; a knative bundle's by the label Knative puts on
      // every pod of the Service, in the namespace its manifest states.
      let source = inspected.get(c.from);
      const caller = checked.find((k) => k.bundle === c.from);
      if (caller) {
        if (caller.namespace === "") {
          throw new Error(
            `connection "${c.name}" (from "${c.from}") env "${env}": Knative Service "${caller.service}" states no ` +
              `metadata.namespace, so no NetworkPolicy can name where its pods run. Set it, so "${b.name}" can admit them`,
          );
        }
        source = { name: caller.namespace, selector: { [KNATIVE_POD_LABEL]: caller.service } };
      }
      if (!source) continue; // another placement; refused above if it touched this bundle
      policies.push(allowEdge(c, source, info, info.podPorts.get(t.port)));
    }
    files.push({ path: `${b.name}/20-networkpolicy.yaml`, content: yamlDocs(policies) });
  }
  // A knative bundle gets the same directory, minus the policy: its manifest,
  // copied unchanged, and the Namespace its Service names when the manifest
  // does not declare it. Nothing enforces who may call a Knative Service
  // (strength "none"), so there is no policy to write. But without these two
  // files every bundle had a directory to `kubectl apply` except the knative
  // ones, and nothing created the namespace their Service lives in.
  for (const b of knative) {
    const info = checked.find((k) => k.bundle === b.name);
    const { path, text, objects } = manifests.get(b.name);
    const declared = objects.some((obj) => isObject(obj, NAMESPACE) && obj.metadata?.name === info.namespace);
    if (info.namespace !== "" && !declared) {
      files.push({ path: `${b.name}/00-namespace.yaml`, content: yamlDocs([namespaceObject(info.namespace)]) });
    }
    files.push({ path: `${b.name}/10-${basename(path)}`, content: text });
  }
  // Where each written directory is applied: a kubernetes bundle in the
  // namespace named after it, a knative one in the namespace its Service
  // states ("" when it states none, and kubectl's current namespace is used).
  const applies = [
    ...placed.map((b) => ({ bundle: b.name, namespace: b.name })),
    ...knative.map((b) => ({ bundle: b.name, namespace: checked.find((k) => k.bundle === b.name).namespace })),
  ];
  return { files, applies, checked, references, unreferenced, unread };
}

/** The files `lowerK8s` writes, for callers that want only those. */
export function emitK8s(opts) {
  return lowerK8s(opts).files;
}
