// cli/lib/cluster/emit-k8s.mjs — the forwarded `kubernetes` placement
// (ADR-0070 §2 + §4, cloister-991e65).
//
// Forwarded means forwarded. The operator's rendered manifest is the workload
// spec; cloister parses it ONLY to check the edges it declares (does the
// Service carry each declared port, by name, number and appProtocol?) and
// copies it byte-for-byte. Everything cloister adds is an overlay of its own
// objects, one namespace per bundle:
//
//   - the Namespace, unless the manifest declares it;
//   - a default-deny-ingress NetworkPolicy for that namespace;
//   - per declared connection INTO the bundle from another kubernetes-placed
//     bundle: a NetworkPolicy admitting the source's pods (namespace + the
//     source Service's selector) to the target's pods (the target Service's
//     selector) on that port, TCP.
//
// That is the `policy` strength of ADR-0070 §3: a reachable peer is refused
// unless an edge was declared. It holds only where the CNI enforces
// NetworkPolicy (kind >= v0.24 does).
//
// No env vars are emitted. Env lowering is a later slice; until then the
// operator's manifest carries the address itself.

import { basename } from "node:path";
import { parseAllDocuments, stringify } from "yaml";

import {
  isExposed,
  placementFor,
  placementManifest,
  refuseCrossPlacement,
} from "./connections.mjs";

const MANAGED_BY = { "app.kubernetes.io/managed-by": "cloister" };
const HEADER = "# Generated by `cloister cluster k8s` (ADR-0070 §4). Do not edit.\n";

/** Parse a multi-document YAML manifest into plain objects, failing by name. */
export function parseManifest(text, label) {
  const docs = parseAllDocuments(text);
  const objects = [];
  for (const doc of docs) {
    if (doc.errors.length > 0) {
      throw new Error(`${label}: YAML parse error: ${doc.errors[0].message}`);
    }
    const obj = doc.toJS();
    if (obj === null || obj === undefined) continue; // empty document
    if (typeof obj !== "object" || Array.isArray(obj) || typeof obj.kind !== "string") {
      throw new Error(`${label}: every document must be a Kubernetes object with a kind`);
    }
    objects.push(obj);
  }
  return objects;
}

function isLabelMap(v) {
  return v && typeof v === "object" && !Array.isArray(v) && Object.keys(v).length > 0
    && Object.values(v).every((x) => typeof x === "string");
}

/**
 * Check one kubernetes-placed bundle's manifest against its declarations, and
 * return what the overlay needs: whether it declares its own Namespace, the
 * Service selector, and each declared port's pod-side port.
 */
export function inspectManifest(bundle, objects, label) {
  const ns = bundle.name;
  let declaresNamespace = false;
  const services = [];
  for (const obj of objects) {
    const name = obj.metadata?.name ?? "<unnamed>";
    if (obj.kind === "Namespace") {
      if (name !== ns) {
        throw new Error(
          `${label}: declares Namespace "${name}", but bundle "${ns}" lives in namespace "${ns}" ` +
            `(one namespace per bundle, named after it)`,
        );
      }
      declaresNamespace = true;
      continue;
    }
    const objNs = obj.metadata?.namespace;
    if (objNs !== undefined && objNs !== ns) {
      throw new Error(
        `${label}: ${obj.kind} "${name}" is in namespace "${objNs}", but bundle "${ns}"'s ` +
          `objects must be in namespace "${ns}" or declare none`,
      );
    }
    if (obj.kind === "Service") services.push(obj);
  }

  if (services.length !== 1) {
    throw new Error(
      `${label}: bundle "${ns}" must declare exactly one Service (found ${services.length}); ` +
        `its selector is what the NetworkPolicies select`,
    );
  }
  const svc = services[0];
  const svcName = svc.metadata?.name ?? "<unnamed>";
  const selector = svc.spec?.selector;
  if (!isLabelMap(selector)) {
    throw new Error(`${label}: Service "${svcName}" has no spec.selector; NetworkPolicies need one to select pods`);
  }

  const podPorts = new Map();
  const svcPorts = Array.isArray(svc.spec?.ports) ? svc.spec.ports : [];
  for (const p of bundle.ports.filter(isExposed)) {
    if (p.expose === "edge") {
      // Publishing a port outside the cluster (a NodePort plus kind
      // extraPortMappings) overlaps the broker work; refused, not guessed.
      throw new Error(
        `${label}: bundle "${ns}" port "${p.name}" has expose = "edge", which \`cluster k8s\` does ` +
          `not lower yet (a NodePort plus kind extraPortMappings; tracked with cloister-55424e). ` +
          `Use expose = "cluster" for a kubernetes placement, or place the bundle microvm, where ` +
          `\`cluster up\` publishes it on 127.0.0.1.`,
      );
    }
    const sp = svcPorts.find((x) => x?.name === p.name);
    const where = `${label}: Service "${svcName}" port "${p.name}"`;
    if (!sp) {
      throw new Error(`${where} is missing — bundle "${ns}" declares port "${p.name}" (${p.port}) with expose "${p.expose}"`);
    }
    if (sp.port !== p.port) {
      throw new Error(`${where} has port ${sp.port}, but cluster.toml declares ${p.port}`);
    }
    if (sp.appProtocol !== p.appProtocol) {
      throw new Error(
        `${where} has appProtocol ${JSON.stringify(sp.appProtocol ?? null)}, but cluster.toml declares "${p.appProtocol}"`,
      );
    }
    // NetworkPolicy ports match the POD's port, which is the Service's
    // targetPort (a number or a container port name), defaulting to `port`.
    podPorts.set(p.name, sp.targetPort ?? sp.port);
  }
  return { declaresNamespace, selector, podPorts };
}

function namespaceObject(ns) {
  return { apiVersion: "v1", kind: "Namespace", metadata: { name: ns, labels: { ...MANAGED_BY } } };
}

function defaultDeny(ns) {
  return {
    apiVersion: "networking.k8s.io/v1",
    kind: "NetworkPolicy",
    metadata: { name: "cloister-default-deny-ingress", namespace: ns, labels: { ...MANAGED_BY } },
    spec: { podSelector: {}, policyTypes: ["Ingress"] },
  };
}

function allowEdge(conn, source, target, podPort) {
  return {
    apiVersion: "networking.k8s.io/v1",
    kind: "NetworkPolicy",
    metadata: {
      name: `cloister-allow-${conn.from}-${conn.name}`,
      namespace: target.name,
      labels: { ...MANAGED_BY },
    },
    spec: {
      podSelector: { matchLabels: { ...target.selector } },
      policyTypes: ["Ingress"],
      ingress: [
        {
          from: [
            {
              namespaceSelector: { matchLabels: { "kubernetes.io/metadata.name": source.name } },
              podSelector: { matchLabels: { ...source.selector } },
            },
          ],
          ports: [{ protocol: "TCP", port: podPort }],
        },
      ],
    },
  };
}

function yamlDocs(objects) {
  return HEADER + objects.map((o) => stringify(o, { lineWidth: 0 })).join("---\n");
}

/**
 * Lower every kubernetes-placed bundle for `env`.
 *
 * @param {object} opts
 * @param {Array} opts.bundles   checkable bundles (name, ports, placements, executionMode)
 * @param {Array} opts.connections normalized connections
 * @param {string} opts.env
 * @param {(path: string) => string} opts.readManifest reads a cluster-dir-relative path
 * @returns {Array<{path: string, content: string}>} deterministic: bundles in
 *   declaration order, files `<bundle>/00-namespace.yaml` (when needed),
 *   `<bundle>/10-<manifest basename>`, `<bundle>/20-networkpolicy.yaml`.
 */
export function emitK8s({ bundles, connections, env, readManifest }) {
  const placed = bundles.filter((b) => placementFor(b, env) === "kubernetes");

  // Edges that touch a kubernetes bundle: both ends must be kubernetes here.
  // An edge into or out of another placement is legal in the graph and
  // refused by every emitter until LLO's broker exists.
  for (const c of connections) {
    const from = bundles.find((b) => b.name === c.from);
    const fromKind = placementFor(from, env);
    const target = c.targets.find((t) => t.env === env);
    if (!target) {
      if (fromKind === "kubernetes") {
        throw new Error(
          `connection "${c.name}" (from "${c.from}") declares no target for env "${env}" ` +
            `(declared: ${c.targets.map((t) => t.env).join(", ")})`,
        );
      }
      continue;
    }
    const toKind = placementFor(bundles.find((b) => b.name === target.bundle), env);
    if (fromKind !== "kubernetes" && toKind !== "kubernetes") continue;
    if (fromKind !== toKind) refuseCrossPlacement(c, c.from, fromKind, target.bundle, toKind, env);
  }

  const inspected = new Map();
  const texts = new Map();
  for (const b of placed) {
    const path = placementManifest(b, env);
    const label = `bundle "${b.name}" manifest ${path}`;
    const text = readManifest(path);
    texts.set(b.name, { path, text });
    inspected.set(b.name, { name: b.name, ...inspectManifest(b, parseManifest(text, label), label) });
  }

  const files = [];
  for (const b of placed) {
    const info = inspected.get(b.name);
    const { path, text } = texts.get(b.name);
    if (!info.declaresNamespace) {
      files.push({ path: `${b.name}/00-namespace.yaml`, content: yamlDocs([namespaceObject(b.name)]) });
    }
    files.push({ path: `${b.name}/10-${basename(path)}`, content: text });

    const policies = [defaultDeny(b.name)];
    for (const c of connections) {
      const t = c.targets.find((x) => x.env === env);
      if (!t || t.bundle !== b.name) continue;
      const source = inspected.get(c.from);
      if (!source) continue; // not kubernetes-placed; refused above if it touched this bundle
      policies.push(allowEdge(c, source, info, info.podPorts.get(t.port)));
    }
    files.push({ path: `${b.name}/20-networkpolicy.yaml`, content: yamlDocs(policies) });
  }
  return files;
}
